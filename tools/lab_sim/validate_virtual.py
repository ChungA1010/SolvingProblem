"""Posterior predictive check of the virtual tool against held-out fold 5 (issue #6).

Parameters come from folds 1..4 only (state-model-v2.json + wear/pressure range estimated here
on folds 1..4). Fold 5 keeps its real order, recipes, pressures, pad counters and rest / pad-change
events; only the MRR values are regenerated by the virtual tool, many times. Every statistic of the
real fold 5 is then compared with the spread of the virtual replicas.

Usage: python -m tools.lab_sim.validate_virtual --wafer-table <wafer_table.csv> --out runs/lab_sim_virtual_tool
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from .evaluate import ewma_features, run_state_model
from .features import add_context, contexts, load_table, pad_step_from
from .state_model import ModelParams, StateModel
from .virtual_tool import ReversionParams, VirtualParams, VirtualTool, WearParams

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / "ui-redesign" / "dist" / "lab-sim" / "state-model-v2.json"
RECIPES = ("A456", "B456")


def estimate_wear(train: pd.DataFrame) -> dict[str, WearParams]:
    """Within-pad-life slope of MRR on pad usage (life fixed effects), training rows only."""
    t = train.sort_values("t_start").copy()
    t["life"] = (t.u_pad.diff() < -5).cumsum()
    out = {}
    for rec in RECIPES:
        g = t[(t.recipe == rec) & (t.groupby("life").mrr.transform("size") >= 8)]
        y = g.mrr - g.groupby("life").mrr.transform("mean")
        x = g.u_pad - g.groupby("life").u_pad.transform("mean")
        out[rec] = WearParams(slope=float((x * y).sum() / (x * x).sum()), ref_usage=float(g.u_pad.mean()))
    return out


def estimate_reversion(train: pd.DataFrame, params: ModelParams) -> dict[str, ReversionParams]:
    """Stationary spread from the median within-fold variance (robust to one regime-change fold);
    the level reverts to the most recent training fold's mean (current operating regime)."""
    out = {}
    for rec in RECIPES:
        t = train[train.recipe == rec]
        p = params.recipes[rec]
        var_level = max(float(t.groupby("fold").mrr.var().median()) - p.r, 2 * p.q)
        out[rec] = ReversionParams(phi=float(np.sqrt(1 - p.q / var_level)), mu=float(t[t.fold == t.fold.max()].mrr.mean()))
    return out


def pressure_range(dev: pd.DataFrame) -> dict[str, tuple[float, float]]:
    """Allowed setpoints: 1st-99th percentile of observed main pressure in the development data."""
    return {r: tuple(float(v) for v in dev[dev.recipe == r].p_main.quantile([0.01, 0.99])) for r in RECIPES}


def recipe_stats(w: pd.DataFrame, mask: np.ndarray, pre: np.ndarray, life: pd.Series) -> dict:
    out = {}
    for rec in RECIPES:
        m = mask & (w.recipe == rec).to_numpy()
        y = w.mrr.to_numpy()[m]
        d = {"mean": y.mean(), "sd": y.std()}
        for k in (1, 2, 4, 8):
            d[f"variogram_k{k}"] = np.var(y[k:] - y[:-k])
        dy = np.diff(y)
        d["lag1_autocorr_of_diff"] = np.corrcoef(dy[1:], dy[:-1])[0, 1]
        lf = life[m].to_numpy(); u = w.u_pad.to_numpy()[m]
        df = pd.DataFrame({"y": y, "u": u, "life": lf})
        df = df[df.groupby("life").y.transform("size") >= 4]
        yy = df.y - df.groupby("life").y.transform("mean"); uu = df.u - df.groupby("life").u.transform("mean")
        d["wear_slope_per100"] = float((uu * yy).sum() / (uu * uu).sum() * 100) if (uu * uu).sum() > 0 else np.nan
        ev = (w.after_rest | w.after_pad_change).to_numpy()[m]
        d["after_event_residual"] = float(np.mean(y[ev] - pre[m][ev])) if ev.any() else np.nan
        out[rec] = d
    return out


def predictive(model_params: ModelParams, w: pd.DataFrame, mask: np.ndarray) -> dict:
    y = w.mrr.to_numpy()
    out = {}
    for name, N, k in (("N=0", 0, 1), ("N=2", 2, 1), ("every 5", 0, 5)):
        pre, _ = run_state_model(StateModel(model_params), w, N, k)
        m = mask & ~np.isnan(pre[:, 0])
        out[f"kalman_mae {name}"] = float(np.mean(np.abs(y[m] - pre[m, 0])))
        if name == "N=0":
            out["kalman_coverage90 N=0"] = float(np.mean((y[m] >= pre[m, 1]) & (y[m] <= pre[m, 2])))
            n0 = pre
        prev, ewm = ewma_features(w, N, k)
        me = mask & ~np.isnan(ewm)
        out[f"ewma_mae {name}"] = float(np.mean(np.abs(y[me] - ewm[me])))
    return out, n0


def validate(table: Path, out: Path, replicas: int):
    raw = load_table(table)
    pad_step = pad_step_from(raw[raw.fold < 5])
    w = add_context(raw, pad_step)
    params = ModelParams.from_json(json.loads(MODEL.read_text(encoding="utf-8")))
    train = w[w.fold < 5]
    # Generator parameters use folds 1..4 only; the pressure range is a UI bound, not used in this check.
    vp = VirtualParams(model=params, wear=estimate_wear(train), reversion=estimate_reversion(train, params),
                       pressure_range=pressure_range(w))
    life = (w.sort_values("t_start").u_pad.diff() < -5).cumsum().reindex(w.index)
    mask = (w.fold == 5).to_numpy()

    # Operator belief at the end of fold 4 (fully measured), used to draw the hidden starting level.
    warm = StateModel(params)
    for ctx, row in zip(contexts(train), train.itertuples()):
        warm.update(ctx, float(row.mrr), float(row.p_main))
    init = {r: (warm.trackers[r].level, warm.trackers[r].var) for r in RECIPES}

    def summarize(frame):
        pred, n0 = predictive(params, frame, mask)
        st = recipe_stats(frame, mask, n0[:, 0], life)
        flat = {f"{r} {k}": v for r, d in st.items() for k, v in d.items()}
        flat.update(pred)
        return flat

    real = summarize(w)
    sims = []
    session = w[mask]
    for s in range(replicas):
        tool = VirtualTool(vp, init, seed=1000 + s)
        mrr = [tool.wafer(r.recipe, r.p_main, r.after_rest, r.after_pad_change, r.u_pad)["mrr"] for r in session.itertuples()]
        syn = w.copy(); syn.loc[mask, "mrr"] = mrr
        sims.append(summarize(syn))
    sims = pd.DataFrame(sims)
    rows = []
    for key, val in real.items():
        lo, med, hi = np.nanpercentile(sims[key], [5, 50, 95])
        rows.append({"statistic": key, "real_fold5": val, "virtual_p05": lo, "virtual_median": med, "virtual_p95": hi,
                     "inside_90pct_band": bool(lo <= val <= hi)})
    table_out = pd.DataFrame(rows)
    out.mkdir(parents=True, exist_ok=True)
    table_out.to_csv(out / "posterior_predictive_check.csv", index=False)
    payload = {"replicas": replicas, "fitted_on": "folds 1-4", "checked_against": "fold 5 (held out from fitting)",
               "virtual_params": vp.to_json(), "inside_band": int(table_out.inside_90pct_band.sum()), "statistics": len(table_out)}
    (out / "virtual_params.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    pd.set_option("display.width", 160)
    print(table_out.round(3).to_string(index=False))
    print(f"\ninside 5-95% band: {payload['inside_band']}/{payload['statistics']}")
    print(json.dumps(vp.to_json(), indent=1))
    return table_out


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--wafer-table", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=Path("runs/lab_sim_virtual_tool"))
    ap.add_argument("--replicas", type=int, default=150)
    a = ap.parse_args()
    validate(a.wafer_table, a.out, a.replicas)
